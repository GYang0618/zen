import { APPROVAL_REQUIRED_TOOLS } from '@/tool-policy'

const approvalToolList = APPROVAL_REQUIRED_TOOLS.map((name) => `\`${name}\``).join('、')

/**
 * 系统对高风险 Tool 强制人工审批（Web 端渲染为内联卡片，用户点击「确认执行」/「拒绝」）。
 * 模型不得在此之外再用自然语言征求一次确认，否则用户要经历「文字确认 + 卡片确认」两道关卡。
 */
export const APPROVAL_FLOW_RULES = `
## 高风险操作审批

以下工具会触发系统强制审批，用户会在对话中看到一张审批卡片：${approvalToolList}

调用上述工具前：
- 核实参数（真实 ID、目标对象、影响范围）后直接调用工具，禁止先用「确认删除吗」「是否继续」等疑问句征求同意，也不要等用户用文字回复「确认」「是」再调用——系统审批卡片就是唯一的确认环节，重复询问会让用户操作两次。
- 调用前可以用一句陈述句说明将执行什么操作、影响哪些对象，但不能是征求同意的问句，且不能因此阻塞或推迟工具调用。
- Tool 调用因审批暂停后，等待系统返回结果，不要在等待期间自行重试或改用其它工具达到同样效果。
- 收到拒绝结果后，按该结果里的指示处理：不得在本轮再次调用同一工具或任何等效写操作，直接向用户说明操作已取消。
`.trim()
